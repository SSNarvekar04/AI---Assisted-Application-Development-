"""Core logic for the AI-Powered Student Virtual Assistant.

This module contains NO Streamlit code, so it can be tested from the command
line (see run_tests.py). The API key is read from an environment variable on
the server side only; it is never sent to the browser or printed.

Two modes:
  * LIVE mode - ANTHROPIC_API_KEY is set, replies come from a real AI model.
  * DEMO mode - no key; a few pre-written sample answers are returned and every
    one of them is clearly labelled as NOT generated by an AI model.
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass

try:  # python-dotenv lets a local .env file supply the variables
    from dotenv import load_dotenv

    load_dotenv()
except ImportError:  # pragma: no cover - optional at runtime
    pass

DEFAULT_MODEL = "claude-sonnet-5-5"
MAX_INPUT_CHARS = 2000
MAX_HISTORY_MESSAGES = 20
MAX_OUTPUT_TOKENS = 1024
REQUEST_TIMEOUT_SECONDS = 60

EXAMPLE_QUESTIONS = [
    "Explain machine learning in simple terms.",
    "Explain synchronous vs asynchronous JavaScript.",
    "Give me a simple 5-step plan to revise for exams.",
]

SYSTEM_PROMPT = """\
You are "Study Buddy", a friendly, patient virtual tutor for college students \
(undergraduate level). You live inside a small study-help web app built for a \
college practical project.

SCOPE
- Academic topics: science, mathematics, computer science, engineering, \
commerce and humanities.
- Programming concepts: Python, JavaScript, Java, C/C++, SQL, web development, \
data structures and algorithms.
- Study skills: revision plans, note-taking, exam preparation, time management, \
academic writing.

HOW TO ANSWER
1. Start with a one- or two-sentence plain-language answer, then add detail.
2. Use simple language. Define jargon the first time you use it. Add one \
concrete, everyday analogy or example when it helps.
3. For programming questions, include a short, correct, runnable example in a \
fenced code block with the language name, and explain what it does.
4. Keep answers focused: usually under 250 words unless the student asks for \
more depth. Use short paragraphs or bullet points.
5. For longer explanations, end with a one-line summary or a quick check \
question the student can try.

HONESTY RULES
- If the question is vague, ambiguous, or refers to something you cannot see \
(for example "Explain it" or "Fix this" with no earlier context), do NOT guess. \
Ask ONE short clarifying question and say what you need.
- If you are unsure or lack reliable information, say so plainly. Never invent \
facts, formulas, statistics, citations or URLs. Suggest checking the textbook, \
lecture notes or official documentation.
- You cannot see the student's syllabus, grades or files unless they paste \
the relevant text into the chat.

ACADEMIC INTEGRITY
- Help the student learn. Explain concepts and guide their approach. For graded \
assignments, give hints and worked examples of similar problems instead of \
writing a complete submission for them.

PRIVACY AND SAFETY
- Remind students not to share passwords, API keys, ID numbers or other \
sensitive personal data in the chat.
- If a student seems distressed or overwhelmed, respond kindly and encourage \
them to talk to a trusted person or their college counsellor.
- Politely decline requests that are harmful or unrelated to learning.
"""


class AssistantError(Exception):
    """Raised with a student-friendly message when a reply cannot be produced."""


@dataclass
class Reply:
    text: str
    mode: str  # "live" or "demo"
    model: str | None = None


# --------------------------------------------------------------------------
# Configuration helpers
# --------------------------------------------------------------------------
def get_api_key() -> str | None:
    """Return the API key from the environment, or None if missing/placeholder."""
    key = os.getenv("ANTHROPIC_API_KEY", "").strip()
    if not key or key.lower().startswith("your_") or key == "...":
        return None
    return key


def is_live() -> bool:
    return get_api_key() is not None


def get_model() -> str:
    return os.getenv("ANTHROPIC_MODEL", "").strip() or DEFAULT_MODEL


# --------------------------------------------------------------------------
# Live mode
# --------------------------------------------------------------------------
def _friendly_error(exc: Exception) -> str:
    """Translate an SDK/network exception into a message a student can act on."""
    name = type(exc).__name__
    status = getattr(exc, "status_code", None)
    if name == "AuthenticationError" or status in (401, 403):
        return ("The API key was rejected. Check ANTHROPIC_API_KEY in your .env "
                "file (no quotes or extra spaces) and restart the app.")
    if name == "RateLimitError" or status == 429:
        return "Too many requests or usage limit reached. Wait a minute and try again."
    if name in ("APIConnectionError", "APITimeoutError", "ConnectionError", "TimeoutError"):
        return "Could not reach the AI service. Check your internet connection and try again."
    if name == "NotFoundError" or status == 404:
        return ("The configured model was not found. Set ANTHROPIC_MODEL in .env "
                "to a model name your account can use.")
    if name == "InternalServerError" or (isinstance(status, int) and status >= 500):
        return "The AI service is having problems right now. Please try again shortly."
    if name == "BadRequestError" or status == 400:
        return "The request was rejected by the AI service. Try rephrasing or clearing the conversation."
    return "Something went wrong while contacting the AI service. Please try again."


def _call_claude(messages: list[dict]) -> str:
    try:
        import anthropic
    except ImportError as exc:
        raise AssistantError(
            "The 'anthropic' package is not installed. Run: pip install -r requirements.txt"
        ) from exc

    trimmed = messages[-MAX_HISTORY_MESSAGES:]
    while trimmed and trimmed[0]["role"] != "user":  # API expects a user turn first
        trimmed = trimmed[1:]

    try:
        client = anthropic.Anthropic(api_key=get_api_key(), timeout=REQUEST_TIMEOUT_SECONDS)
        response = client.messages.create(
            model=get_model(),
            max_tokens=MAX_OUTPUT_TOKENS,
            system=SYSTEM_PROMPT,
            messages=trimmed,
        )
    except Exception as exc:  # mapped to a friendly message; details never include the key
        raise AssistantError(_friendly_error(exc)) from exc

    text = "".join(
        block.text for block in response.content if getattr(block, "type", "") == "text"
    ).strip()
    if not text:
        raise AssistantError("The AI returned an empty response. Please try rephrasing your question.")
    return text


# --------------------------------------------------------------------------
# Demo mode (NOT an AI model - fixed, pre-written sample text)
# --------------------------------------------------------------------------
DEMO_LABEL = (
    "\U0001F9EA **DEMO MODE - this is a pre-written sample response, "
    "NOT generated by an AI model.**\n\n"
)

_DEMO_ML = """\
**Machine learning in simple terms**

Machine learning (ML) is a way of getting computers to **learn patterns from \
examples** instead of following rules that a programmer wrote by hand.

**Analogy:** to teach a child what a mango looks like, you do not list \
rules - you show many mangoes and other fruits and say which is which. After \
enough examples the child recognises new mangoes. ML works the same way.

**Three basic steps**
1. **Collect data** - for example thousands of emails labelled "spam" or "not spam".
2. **Train** - an algorithm adjusts itself to make fewer mistakes on that data.
3. **Predict** - the trained model is used on new data it has never seen.

**Common types:** supervised learning (learns from labelled examples), \
unsupervised learning (finds groups in unlabelled data) and reinforcement \
learning (learns by trial, error and rewards).

**Everyday examples:** spam filters, movie recommendations, face unlock.

**Summary:** ML = learning from data to make predictions, instead of coding every rule.
"""

_DEMO_ASYNC = """\
**Synchronous vs asynchronous JavaScript**

- **Synchronous** code runs line by line; each line must finish before the next starts.
- **Asynchronous** code lets slow work (timers, network requests) happen in the \
background while the rest of the program keeps running.

```javascript
console.log("1: Start");
setTimeout(() => console.log("2: Timer finished"), 1000);
console.log("3: End");
// Output order: 1: Start, 3: End, 2: Timer finished
```

The timer is asynchronous, so "3: End" prints before the timer callback.

**Modern style with async/await**
```javascript
async function loadUser() {
  const response = await fetch("https://example.com/api/user");
  const user = await response.json();
  console.log(user);
}
```
`await` pauses only this function until the Promise settles; the page stays responsive.

**Summary:** synchronous = wait and then continue; asynchronous = start the \
task, keep working, handle the result when it arrives (callbacks, Promises, async/await).
"""

_DEMO_STUDY = """\
**A simple 5-step revision plan**
1. **List the topics** from your syllabus and mark each one Strong / Medium / Weak.
2. **Plan backwards** from the exam date and give weak topics the most time.
3. **Study in short blocks** (for example 25-45 minutes) with 5-10 minute breaks.
4. **Practise, don't just reread** - solve past papers and explain topics aloud from memory.
5. **Review** - go back over mistakes after 1 day, 1 week and just before the exam.

Also sleep properly and keep the day before the exam light.
"""

_DEMO_CLARIFY = """\
Your message says "it", but I don't have anything earlier in this conversation \
to know what "it" refers to.

**Which topic or concept would you like me to explain?** For example: \
"Explain recursion in Python" or "Explain Ohm's law".
"""

_DEMO_FALLBACK = """\
I'm running in **demo mode**, so I only have a few pre-written sample answers \
and can't answer this question.

To get real answers to any question:
1. Get an API key from your AI provider.
2. Copy `.env.example` to `.env` and put the key in `ANTHROPIC_API_KEY`.
3. Restart the app. The sidebar will switch to "Live AI mode".

Meanwhile, try one of the example questions above.
"""

_VAGUE = re.compile(
    r"^\s*(explain|describe|summari[sz]e|solve|fix|help( me)?( with)?|tell me about)?\s*"
    r"(it|this|that|these|those|them)\s*[.?!]*\s*$",
    re.IGNORECASE,
)


def _demo_reply(messages: list[dict]) -> str:
    question = messages[-1]["content"].strip()
    lower = question.lower()
    has_earlier_turns = len(messages) > 1

    if _VAGUE.match(question) and not has_earlier_turns:
        body = _DEMO_CLARIFY
    elif "machine learning" in lower:
        body = _DEMO_ML
    elif ("synchronous" in lower or "async" in lower) and ("javascript" in lower or "js" in lower):
        body = _DEMO_ASYNC
    elif any(word in lower for word in ("revise", "revision", "exam", "study plan")):
        body = _DEMO_STUDY
    else:
        body = _DEMO_FALLBACK
    return DEMO_LABEL + body


# --------------------------------------------------------------------------
# Public entry point
# --------------------------------------------------------------------------
def generate_reply(messages: list[dict]) -> Reply:
    """messages: [{"role": "user"|"assistant", "content": str}, ...]; last one is the new question."""
    if not messages or messages[-1]["role"] != "user":
        raise AssistantError("Nothing to answer - please type a question first.")
    question = messages[-1]["content"].strip()
    if not question:
        raise AssistantError("Please type a question first.")
    if len(question) > MAX_INPUT_CHARS:
        raise AssistantError(f"Your question is too long. Please keep it under {MAX_INPUT_CHARS} characters.")

    if is_live():
        return Reply(text=_call_claude(messages), mode="live", model=get_model())
    return Reply(text=_demo_reply(messages), mode="demo")
