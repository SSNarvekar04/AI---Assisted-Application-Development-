"""Streamlit UI for the AI-Powered Student Virtual Assistant.

Run with:  streamlit run app.py
All AI logic lives in assistant.py; the API key is only ever read server-side.
"""
import streamlit as st

import assistant as bot

st.set_page_config(page_title="Student Virtual Assistant", page_icon="\U0001F393", layout="centered")


# ---------------------------------------------------------------- state
st.session_state.setdefault("messages", [])  # [{"role", "content", "mode", "error"}]
st.session_state.setdefault("pending", None)  # question waiting to be answered
st.session_state.setdefault("empty_warning", False)


def on_send():
    text = st.session_state.get("user_input", "").strip()
    if text:
        st.session_state.pending = text
    else:
        st.session_state.empty_warning = True


def on_example(question: str):
    st.session_state.pending = question


def on_clear():
    st.session_state.messages = []
    st.session_state.pending = None
    st.session_state.empty_warning = False


def api_history():
    """Messages sent to the model: error bubbles are display-only and excluded."""
    return [
        {"role": m["role"], "content": m["content"]}
        for m in st.session_state.messages
        if not m.get("error")
    ]


def show_message(message: dict):
    with st.chat_message(message["role"]):
        if message.get("error"):
            st.error(message["content"])
        else:
            st.markdown(message["content"])
            if message["role"] == "assistant" and message.get("mode") == "demo":
                st.caption("Demo response - not generated by an AI model")


# ---------------------------------------------------------------- sidebar
with st.sidebar:
    st.header("Status")
    if bot.is_live():
        st.success(f"Live AI mode\n\nModel: `{bot.get_model()}`")
    else:
        st.warning(
            "**DEMO MODE** - no API key found.\n\n"
            "Replies are pre-written samples, **not** real AI output. "
            "To connect a real model: copy `.env.example` to `.env`, set "
            "`ANTHROPIC_API_KEY`, and restart the app."
        )
    st.caption("Do not enter passwords, ID numbers or other private data.")

# ---------------------------------------------------------------- header
st.title("\U0001F393 Student Virtual Assistant")
st.caption("Ask about academic topics, programming concepts or study techniques.")

st.write("**Try an example question:**")
for i, question in enumerate(bot.EXAMPLE_QUESTIONS):
    st.button(question, key=f"example_{i}", on_click=on_example, args=(question,))

st.divider()

# ---------------------------------------------------------------- conversation
for message in st.session_state.messages:
    show_message(message)

if st.session_state.pending:
    question = st.session_state.pending
    st.session_state.pending = None
    user_message = {"role": "user", "content": question}
    st.session_state.messages.append(user_message)
    show_message(user_message)

    with st.chat_message("assistant"):
        try:
            with st.spinner("Thinking..."):
                reply = bot.generate_reply(api_history())
            assistant_message = {"role": "assistant", "content": reply.text, "mode": reply.mode}
            st.markdown(reply.text)
            if reply.mode == "demo":
                st.caption("Demo response - not generated by an AI model")
        except bot.AssistantError as exc:
            assistant_message = {"role": "assistant", "content": str(exc), "error": True}
            st.error(str(exc))
        except Exception:  # last-resort guard so the app never shows a raw traceback
            assistant_message = {
                "role": "assistant",
                "content": "Unexpected error. Please try again or clear the conversation.",
                "error": True,
            }
            st.error(assistant_message["content"])
    st.session_state.messages.append(assistant_message)

# ---------------------------------------------------------------- input
if st.session_state.empty_warning:
    st.warning("Please type a question before pressing Send.")
    st.session_state.empty_warning = False

with st.form("chat_form", clear_on_submit=True):
    st.text_input(
        "Your question",
        key="user_input",
        placeholder="e.g. What is the difference between a list and a tuple in Python?",
        max_chars=bot.MAX_INPUT_CHARS,
    )
    st.form_submit_button("Send", on_click=on_send)

st.button("\U0001F5D1\uFE0F Clear conversation", on_click=on_clear)
